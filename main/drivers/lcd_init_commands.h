struct InitCommand
{
    int command;
    std::span<const std::uint8_t> data;
    unsigned delay_ms;
};

template <std::uint8_t... Bytes>
inline constexpr std::array<std::uint8_t, sizeof...(Bytes)> COMMAND_DATA{Bytes...};

template <std::uint8_t... Bytes>
constexpr InitCommand command(int code, unsigned delay_ms = 0)
{
    return {code, COMMAND_DATA<Bytes...>, delay_ms};
}

